#!/usr/bin/env bash
# sync-comp.sh — refresh the vendored niri snapshot in comp/ from upstream main.
#
# Deliberate, not automatic: each run produces a reviewable diff of upstream's
# changes against our tree. Commit the result separately from our own work.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
UPSTREAM="${UPSTREAM:-https://github.com/niri-wm/niri}"
SRC="${SRC:-/tmp/niri-sync}"

rm -rf "$SRC"
git clone --depth 1 "$UPSTREAM" "$SRC"
SHA="$(git -C "$SRC" rev-parse HEAD)"
DATE="$(git -C "$SRC" log -1 --format=%cs)"

rm -rf "$ROOT/comp"
mkdir -p "$ROOT/comp"
(cd "$SRC" && tar --exclude=.git -cf - .) | tar -xf - -C "$ROOT/comp"

cat > "$ROOT/comp/VENDORED.md" <<EOF
# Vendored: niri (cosmos-comp base)

This directory is a snapshot of upstream niri — the compositor Solyra forks
(ADR-0002 in docs/decisions.md).

- Upstream: https://github.com/niri-wm/niri (branch main, GPL-3.0)
- Fork (push target for our patches): https://github.com/PupppyLoverr/niri
- Pinned upstream commit: $SHA ($DATE)

Everything in this directory is GPL-3.0; Solyra's patches to it stay GPL-3.0.
Regenerated by scripts/sync-comp.sh on every sync — edit nothing below this
line except via the script's template.
EOF

echo "comp/ refreshed to upstream $SHA ($DATE)"
echo "review:  git diff --stat -- comp"
